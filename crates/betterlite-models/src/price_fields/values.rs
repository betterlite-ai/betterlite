use rust_decimal::Decimal;
use serde::{Deserialize, Serialize};

macro_rules! price_values {
    ($($field:ident: $wire:literal => $parser:literal),* $(,)?) => {
        #[derive(Clone, Debug, Default, Eq, PartialEq, Serialize, Deserialize)]
        #[serde(default)]
        pub struct PricingValues {
            $(
                #[serde(rename = $wire, deserialize_with = $parser, skip_serializing_if = "Option::is_none")]
                pub $field: Option<Decimal>,
            )*
        }
        impl PricingValues {
            $(
                fn $field<'de, Deserializer>(
                    deserializer: Deserializer,
                ) -> Result<Option<Decimal>, Deserializer::Error>
                where Deserializer: serde::Deserializer<'de>
                {
                    let price = super::deserialize::read_price(deserializer, $wire)?;
                    Ok(Some(price))
                }
            )*
        }
    };
}

