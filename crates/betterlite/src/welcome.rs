const DIVIDER_CHAR: char = '\u{254c}';

pub fn print_welcome(
    version: &str,
    supports_color: bool,
    writer: &mut dyn Write,
) -> io::Result<()> {
    writeln!(writer)?;
    writeln!(writer, "{}", orange(LITELLM_ASCII, supports_color))?;
    writeln!(
        writer,
        "  {} to {} {}",
        orange("Welcome", supports_color),
        bold("LiteLLM", supports_color),
        grey(&format!("v{version}"), supports_color)
    )?;
    writeln!(writer)?;
    writeln!(
        writer,
        "{}",
        dim(
            &format!("  {}", DIVIDER_CHAR.to_string().repeat(74)),
            supports_color
        )
    )?;
    writeln!(writer)?;
    Ok(())
}

