use std::collections::BTreeMap;

use secrecy::SecretString;

use crate::loader::EnvironmentLookup;

const NAMES: &str = "\
    REDIS_URL REDIS_HOST REDIS_PORT REDIS_USERNAME REDIS_PASSWORD REDIS_DB REDIS_SSL \
    REDIS_MAX_CONNECTIONS REDIS_HEALTH_CHECK_INTERVAL REDIS_SOCKET_KEEPALIVE \
    REDIS_SOCKET_TIMEOUT REDIS_SOCKET_CONNECT_TIMEOUT REDIS_SENTINEL_NODES \
    REDIS_SENTINEL_PASSWORD REDIS_SERVICE_NAME REDIS_CLUSTER_NODES REDIS_SSL_PASSWORD \
    REDIS_CLIENT_NAME REDIS_DECODE_RESPONSES REDIS_ENCODING REDIS_ENCODING_ERRORS \
    REDIS_PROTOCOL REDIS_RETRY_ON_TIMEOUT REDIS_SINGLE_CONNECTION_CLIENT \
    REDIS_SOCKET_READ_SIZE REDIS_SSL_CA_CERTS REDIS_SSL_CA_DATA REDIS_SSL_CA_PATH \
    REDIS_SSL_CERT_REQS REDIS_SSL_CERTFILE REDIS_SSL_CHECK_HOSTNAME REDIS_SSL_CIPHERS \
    REDIS_SSL_KEYFILE REDIS_SSL_MIN_VERSION REDIS_UNIX_SOCKET_PATH \
    REDIS_GCP_SERVICE_ACCOUNT REDIS_GCP_SSL_CA_CERTS REDIS_AZURE_REDIS_AD_TOKEN \
    REDIS_AZURE_AD_TOKEN REDIS_AZURE_CLIENT_ID REDIS_AZURE_TENANT_ID \
    REDIS_AZURE_CLIENT_SECRET AZURE_CLIENT_ID AZURE_TENANT_ID AZURE_CLIENT_SECRET \
    REDIS_AWS_IAM_AUTH REDIS_AWS_IAM_USER_NAME REDIS_AWS_IAM_CACHE_NAME \
    REDIS_AWS_IAM_REGION REDIS_AWS_IAM_SERVERLESS AWS_REGION AWS_DEFAULT_REGION";

pub(super) fn collect<L>(lookup: &L) -> BTreeMap<String, SecretString>
where
    L: EnvironmentLookup,
{
    NAMES
        .split_whitespace()
        .filter_map(|name| {
            let value = lookup.lookup(name).filter(|text| !text.is_empty())?;
            Some((name.to_owned(), SecretString::from(value)))
        })
        .collect()
}
