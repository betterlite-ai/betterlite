use crate::{BugReport, Surface};

pub(crate) fn description(
    report: &BugReport,
    frames: &[String],
    config_lines: &[String],
) -> String {
    let frame_block = if frames.is_empty() {
        String::new()
    } else {
        format!("LiteLLM frames:\n```\n{}\n```\n\n", frames.join("\n"))
    };
    let config_block = if config_lines.is_empty() {
        String::new()
    } else {
        format!(
            "\nConfig (true/false flags and LiteLLM-defined values only):\n```\n{}\n```\n",
            config_lines.join("\n")
        )
    };
    let stream_line = report
        .stream
        .map(|value| format!("Stream: {value}\n"))
        .unwrap_or_default();
    format!(
        "Auto-generated by LiteLLM's bug report link. It carries no request data or error text. Please describe what you were doing, and paste the error message from your log below if it contains nothing sensitive.\n\n```\n\n```\n\nException: `{}`\n\n{}Surface: {}\nEndpoint / call: {}\nProvider: {}\nLiteLLM: {}\nPython: {}\n{}{}",
        report.exception_type,
        frame_block,
        surface_name(report.environment.surface),
        report.call_type.as_deref().unwrap_or("unknown"),
        report.custom_llm_provider.as_deref().unwrap_or("unknown"),
        report.environment.litellm_version,
        report.environment.python_version,
        stream_line,
        config_block
    )
}

const fn surface_name(surface: Surface) -> &'static str {
    match surface {
        Surface::Sdk => "sdk",
        Surface::Proxy => "proxy",
    }
}
