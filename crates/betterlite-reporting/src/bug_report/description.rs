use crate::bug_report::record::BugReport;

pub(crate) fn issue_description(
    report: &BugReport,
    frames: &[String],
    config_lines: &[String],
) -> String {
    let frame_block = if frames.is_empty() {
        String::new()
    } else {
        format!("LiteLLM frames:\n```\n{}\n```\n\n", frames.join("\n"))
    };
    let stream_line = report
        .stream
        .map_or_else(String::new, |stream| format!("Stream: {stream}\n"));
    let config_block = if config_lines.is_empty() {
        String::new()
    } else {
        format!(
            "\nConfig (true/false flags and LiteLLM-defined values only):\n```\n{}\n```\n",
            config_lines.join("\n")
        )
    };
    let environment = &report.environment;
    // Python's `or` turns an empty call type into the placeholder as well
    let call_type = report.call_type.as_deref().filter(|call| !call.is_empty());
    format!(
        "{PREAMBLE}Exception: `{}`\n\n{frame_block}Surface: {}\nEndpoint / call: {}\nProvider: {}\nLiteLLM: {}\nPython: {}\n{stream_line}{config_block}",
        report.exception_type,
        environment.surface.as_str(),
        call_type.unwrap_or("unknown"),
        report.custom_llm_provider.as_deref().unwrap_or("unknown"),
        environment.litellm_version,
        environment.python_version,
    )
}

const PREAMBLE: &str = "Auto-generated by LiteLLM's bug report link. It carries no request data or error text. Please describe what you were doing, and paste the error message from your log below if it contains nothing sensitive.\n\n```\n\n```\n\n";
